goal = (19, 19)

def solve(current: tuple) -> bool:
    row, col = current
    if row < 0 or row >= len(maze) or col < 0 or col >= len(maze[0]):
        return False
    if maze[row][col] == 1 or maze[row][col] == 2:
        return False
    if current == goal:
        return True

    maze[row][col] = 2

    if (solve((row - 1, col)) or
            solve((row + 1, col)) or
            solve((row, col + 1)) or
            solve((row, col - 1))):
        return True

    return False


