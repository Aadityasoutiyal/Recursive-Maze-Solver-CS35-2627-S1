start = (1, 1)
goal = (19, 19)
path = []


def solve(current: tuple) -> bool:
    row, col = current
    if row < 0 or row >= len(maze) or col < 0 or col >= len(maze[0]):
        return False
    if maze[row][col] == 1 or maze[row][col] == 2:
        return False

    path.append(current)

    if current == goal:
        return True

    maze[row][col] = 2

    if (solve((row - 1, col)) or
            solve((row + 1, col)) or
            solve((row, col + 1)) or
            solve((row, col - 1))):
        return True

    path.pop()
    return False


def get_directions(path):
    directions = []
    for i in range(len(path) - 1):
        r1, c1 = path[i]
        r2, c2 = path[i + 1]
        if r2 < r1:
            directions.append('N')
        elif r2 > r1:
            directions.append('S')
        elif c2 > c1:
            directions.append('E')
        elif c2 < c1:
            directions.append('W')
    return directions


def display_maze(original_maze, path, start, goal):
    grid = [row[:] for row in original_maze]
    for r, c in path:
        if (r, c) != start and (r, c) != goal:
            grid[r][c] = '*'

    print("Maze Solved!")
    for r in range(len(grid)):
        row_str = ""
        for c in range(len(grid[0])):
            if (r, c) == start:
                row_str += "S "
            elif (r, c) == goal:
                row_str += "E "
            elif grid[r][c] == 1:
                row_str += "# "
            elif grid[r][c] == '*':
                row_str += "* "
            else:
                row_str += "  "
        print(row_str)


